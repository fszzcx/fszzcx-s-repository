// 实验：传值、传指针、传引用 三种交换方式的对比
// 结论预告：只有【传指针】和【传引用】能真正交换外部变量；
//          【传值】只是在函数内部交换了"复印件"，外部变量纹丝不动。

#include <iostream>

// ---------- 方式一：传值 ----------
// 形参 x、y 是实参 a1、b1 的"复印件"（拷贝）。
// 函数内部交换的是这两份复印件，函数结束时它们被销毁，
// 外部变量 a1、b1 从头到尾没有被碰过 → 交换失败。
void swap_val(int x, int y)
{
    int t = x;   // 用临时变量 t 暂存
    x = y;
    y = t;
}

// ---------- 方式二：传指针 ----------
// 形参 x、y 存的是外部变量的"地址"。*x 就是顺着地址找到的 a2 本尊，
// 所以 *x = *y 改的是原件本身 → 交换成功。
// 调用时必须传地址：swap_ptr(&a2, &b2)
void swap_ptr(int* x, int* y)
{
    int t = *x;   // t 暂存 x 指向的那个变量的值
    *x = *y;
    *y = t;
}

// ---------- 方式三：传引用 ----------
// 形参 x、y 是外部变量 a3、b3 的"别名"（同一块内存的第二个名字）。
// 对 x 的任何操作就是对 a3 的操作 → 交换成功。
// 调用方式和传值一样直接写变量名：swap_ref(a3, b3)，不用取地址。
void swap_ref(int& x, int& y)
{
    int t = x;
    x = y;
    y = t;
}

int main()
{
    // 每组变量初始值相同，方便对比三种方式的效果
    int a1 = 1, b1 = 2;
    std::cout << "传值  调用前: a1=" << a1 << " b1=" << b1 << std::endl;
    swap_val(a1, b1);
    std::cout << "传值  调用后: a1=" << a1 << " b1=" << b1 << "  <-- 没换成功" << std::endl;

    int a2 = 1, b2 = 2;
    std::cout << "传指针调用前: a2=" << a2 << " b2=" << b2 << std::endl;
    swap_ptr(&a2, &b2);      // 注意：要传地址，加 &
    std::cout << "传指针调用后: a2=" << a2 << " b2=" << b2 << "  <-- 交换成功" << std::endl;

    int a3 = 1, b3 = 2;
    std::cout << "传引用调用前: a3=" << a3 << " b3=" << b3 << std::endl;
    swap_ref(a3, b3);        // 注意：直接写变量名，和传值调用长得一模一样
    std::cout << "传引用调用后: a3=" << a3 << " b3=" << b3 << "  <-- 交换成功" << std::endl;

    return 0;
}

/* ============ 思考题答案（写进注释里交作业）============
 * 为什么传值失败、传指针/传引用成功？
 *
 * 传值：函数的形参是实参的一份独立拷贝，拥有自己的内存空间。
 *       函数内的任何修改只作用于这份拷贝，函数返回时拷贝销毁，
 *       外部变量不受影响。
 *
 * 传指针：把外部变量的"地址"交给函数，通过 * 解引用，
 *        函数可以直接读写地址指向的那块内存（即原件本身）。
 *
 * 传引用：形参是外部变量的别名，与实参共用同一块内存，
 *        对形参的操作就是对实参的操作，效果等价于传指针，
 *        但调用写法更简洁、更安全（不会传入空指针）。
 */
